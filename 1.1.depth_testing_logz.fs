#version 330 core
out vec4 FragColor;

in vec2 TexCoords;
in float flogz;  // 从顶点着色器传来的对数深度

uniform sampler2D texture1;

void main()
{    
    FragColor = texture(texture1, TexCoords);
    
    // ========================================================================
    // 写入对数深度到深度缓冲
    // ========================================================================
    // flogz 的范围是 [0, 2]，需要映射到 [0, 1]
    // 这比传统深度有更均匀的精度分布
    // ========================================================================
    gl_FragDepth = clamp(flogz * 0.5, 0.0, 1.0);
}
